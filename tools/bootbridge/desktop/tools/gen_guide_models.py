#!/usr/bin/env python3
"""Validate audited guide-model pins and generate the display-only C table."""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import re


MODELS = {
    "NX30": ("BB_MODEL_NX30", "NX30", "RX3000", ("NX30", "RX3000")),
    "RT3000": ("BB_MODEL_RT3000", "RT3000", "", ("RT3000",)),
    "RC3000": ("BB_MODEL_RC3000", "RC3000", "", ("RC3000",)),
    "RW3000": ("BB_MODEL_RW3000", "RW3000", "RW3010", ("RW3000",)),
}


def c_string(value: str) -> str:
    # UTF-8 wide literals; the cross-build pins both source and execution
    # charsets to UTF-8. This avoids GCC rejecting escaped ASCII \uXXXX.
    out = []
    for char in value:
        if char == "\\":
            out.append("\\\\")
        elif char == "\"":
            out.append("\\\"")
        elif char == "\n":
            out.append("\\n")
        elif char == "\r":
            out.append("\\r")
        elif char == "\t":
            out.append("\\t")
        elif ord(char) < 0x20 or ord(char) == 0x7f:
            out.append("\\x%02x" % ord(char))
        else:
            out.append(char)
    return "L\"" + "".join(out) + "\""


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("guide_models", type=Path)
    parser.add_argument("prepared_bundles", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    raw = args.guide_models.read_bytes()
    guide = json.loads(raw)
    prepared = json.loads(args.prepared_bundles.read_bytes())
    cards = guide.get("models")
    if guide.get("schema") != "bootbridge-guide-models-v1" or not isinstance(cards, list):
        raise SystemExit("invalid guide model schema")
    if prepared.get("schema") != "bootbridge-offline-prepared-bundles-v1" or prepared.get("status") != "PASS":
        raise SystemExit("prepared bundle manifest is not PASS")
    bundles = prepared.get("bundles")
    if not isinstance(bundles, list):
        raise SystemExit("prepared bundle list is invalid")
    seen = set()
    rows = []
    for card in cards:
        card_id = card.get("id")
        if card_id not in MODELS or card_id in seen:
            raise SystemExit("invalid or duplicate guide model: " + repr(card_id))
        seen.add(card_id)
        model_enum, primary, alias, products = MODELS[card_id]
        if (card.get("primary") != primary or card.get("alias") != alias or
                card.get("products") != list(products)):
            raise SystemExit(card_id + ": static guide mapping mismatch")
        version, bytes_, digest = card.get("version"), card.get("bytes"), card.get("sha256")
        url = card.get("url", "")
        if not isinstance(version, str) or not version or type(bytes_) is not int or bytes_ < 1:
            raise SystemExit(card_id + ": invalid version or byte count")
        if not isinstance(digest, str) or not re.fullmatch(r"[0-9a-f]{64}", digest):
            raise SystemExit(card_id + ": invalid SHA-256")
        # Optional official download link: HTTPS only, and the object name must
        # be exactly "<version>.bin" so a card can never point at another build.
        if not isinstance(url, str) or (url and not re.fullmatch(
                r"https://[A-Za-z0-9.-]+/(?:[^\s/?#]+/)*" + re.escape(version) + r"\.bin", url)):
            raise SystemExit(card_id + ": invalid optional URL (https://.../<version>.bin required)")
        matches = []
        for bundle in bundles:
            official = bundle.get("official", {})
            identities = {row.get("product") for row in bundle.get("supported_product_identities", [])}
            if official.get("version") == version and official.get("bytes") == bytes_ and official.get("sha256") == digest:
                matches.append((bundle, identities))
        if len(matches) != 1:
            raise SystemExit(card_id + ": guide fingerprint does not uniquely match one bundle")
        bundle, identities = matches[0]
        if bundle.get("official", {}).get("model") != primary or set(products) != identities:
            raise SystemExit(card_id + ": guide logical product mapping differs from bundle")
        rows.append((card_id, model_enum, primary, alias, version, bytes_, digest, url))
    lines = [
        "/* Generated by tools/gen_guide_models.py; do not edit. */",
        "#ifndef BB_GUIDE_MODELS_GENERATED_H",
        "#define BB_GUIDE_MODELS_GENERATED_H",
        "#define BB_GUIDE_MODELS_SOURCE_SHA256 L\"%s\"" % hashlib.sha256(raw).hexdigest(),
        "static const bb_guide_model bb_guide_models[] = {",
    ]
    for card_id, model_enum, primary, alias, version, bytes_, digest, url in rows:
        lines.append("    {%s,%s,%s,%s,%s,%dULL,%s,%s}," % (
            c_string(card_id), model_enum, c_string(primary), c_string(alias),
            c_string(version), bytes_, c_string(digest), c_string(url)))
    lines.extend([
        "};",
        "#define BB_GUIDE_MODEL_COUNT (sizeof(bb_guide_models)/sizeof(bb_guide_models[0]))",
        "#endif",
        "",
    ])
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("guide_models=%d source_sha256=%s" % (len(rows), sha256(args.output)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
