#!/usr/bin/env python3
"""Build a compiled-metadata catalog and exact SHA-pinned literal sidecar.

Input is a validated assemble_release.py output directory. Only XOR/LITERAL
bytes from .bbprog programs enter BootBridge.rules.dat; identities, hashes,
operations, ranges and matching rules remain compiled C metadata.
"""
from __future__ import annotations
import argparse
import hashlib
import importlib.util
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
SPEC = importlib.util.spec_from_file_location("bb_offline_assembler", HERE / "assemble_release.py")
ASM = importlib.util.module_from_spec(SPEC)
sys.modules[SPEC.name] = ASM
SPEC.loader.exec_module(ASM)

MODEL = {"RT3000":"BB_MODEL_RT3000", "RW3000":"BB_MODEL_RW3000", "RC3000":"BB_MODEL_RC3000", "RX3000":"BB_MODEL_RX3000", "NX30":"BB_MODEL_NX30"}
BOARD = {"HW-A":"BB_BOARD_HW_A", "HW-B":"BB_BOARD_HW_B", "HW-C":"BB_BOARD_HW_C", "HW-D":"BB_BOARD_HW_D"}

def cstr(s: str) -> str:
    return '"' + ''.join("\\%03o" % b for b in s.encode("utf-8")) + '"'

def cbytes(b: bytes) -> str:
    return "{" + ",".join("0x%02x" % x for x in b) + "}"

def read_component(source: pathlib.Path, rel: str) -> bytes:
    p=pathlib.PurePosixPath(rel)
    if p.is_absolute() or not p.parts or any(x in ("", ".", "..") for x in p.parts) or "\\" in rel:
        raise ValueError("component path must be a normalized relative path")
    root=source.resolve(); target=(source/rel).resolve()
    if root not in target.parents:
        raise ValueError("component path escapes assembly directory")
    return target.read_bytes()

def build(source: pathlib.Path, output: pathlib.Path) -> tuple[int,str]:
    evidence = json.loads((source / "evidence.json").read_text(encoding="utf-8"))
    components = {"catalog": read_component(source,evidence["catalog"]["path"])}
    for section in ("inputs", "programs", "payloads"):
        for ident, spec in evidence[section].items():
            components[section + "/" + ident] = read_component(source,spec["path"])
    ASM.validate_evidence(evidence, components)
    identity = ASM._identity(evidence["identity"])
    catalog = ASM.parse_canonical_json(components["catalog"])
    parsed = {}
    for section in ("inputs", "programs", "payloads"):
        parsed[section] = {k:{"bytes":len(components[section+"/"+k]),"sha256":hashlib.sha256(components[section+"/"+k]).hexdigest()} for k in evidence[section]}
        parsed[section]["_bytes"] = {k:components[section+"/"+k] for k in evidence[section]}
    rules = ASM._rule_set(catalog, identity, parsed)
    program_ids = sorted(evidence["programs"])
    offsets, blob = {}, bytearray()
    programs = {}
    for pid in program_ids:
        ops, data, _ = ASM._parse_plan(components["programs/"+pid], 128*1024*1024)
        offsets[pid] = len(blob)
        programs[pid] = ops
        blob.extend(data)
    digest = hashlib.sha256(blob).digest()
    lines = ["/* Generated by tools/build_offline_catalog.py; do not edit. */", "#ifndef BB_OFFLINE_CATALOG_GENERATED_H", "#define BB_OFFLINE_CATALOG_GENERATED_H", "#include <stddef.h>", "#include <stdint.h>", "#define BB_OFFLINE_DATA_SIZE %dULL" % len(blob), "static const unsigned char bb_offline_expected_sha256[32] = %s;" % cbytes(digest)]
    lines += ["#ifndef BB_RELEASE_SET_ID", "#define BB_RELEASE_SET_ID %s" % cstr(identity["release_set"]), "#endif", "#ifndef BB_ENGINE_REVISION", "#define BB_ENGINE_REVISION %dU" % identity["engine"], "#endif"]
    for pi,pid in enumerate(program_ids):
        op_entries=[]
        for kind,off,size,dataoff in programs[pid]:
            kindname={1:"BB_PLAN_COPY",2:"BB_PLAN_LITERAL",3:"BB_PLAN_XOR"}[kind]
            ptr="NULL" if kind == 1 else "bb_offline_data+%dULL" % (offsets[pid]+dataoff)
            op_entries.append("{%s,%dULL,%dULL,%s}"%(kindname,off,size,ptr))
        lines.append("static bb_plan_op bb_offline_ops_%d[] = {"%pi)
        for start in range(0,len(op_entries),4): lines.append(",".join(op_entries[start:start+4])+",")
        lines.append("};")
    for ri,r in enumerate(rules):
        pid=r["program_id"]; iid=r["input_id"]; oid=r["payload_id"]
        ib=components["inputs/"+iid]; ob=components["payloads/"+oid]
        lines.append("static bb_plan_recipe bb_offline_plan_%d = {%s,%dULL,%s,%dULL,%s,bb_offline_ops_%d,%dU};" % (ri,cstr(r["id"]),len(ib),cbytes(hashlib.sha256(ib).digest()),len(ob),cbytes(hashlib.sha256(ob).digest()),program_ids.index(pid),len(programs[pid])))
    lines.append("static const bb_board bb_offline_providers[] = {" + ",".join(BOARD[r["board"]] for r in rules) + "};")
    lines.append("static bb_bundle_rule bb_offline_bundles[] = {")
    for ri,r in enumerate(rules):
        lines.append("{%s,%s,%s,%s,BB_RELEASE_SET_ID,%dU,&bb_offline_plan_%d,&bb_offline_providers[%d],1U},"%(cstr(r["id"]),MODEL[r["model"]],cstr(r["model"]),cstr(r["official_version"]),r["minimum_engine_revision"],ri,ri))
    lines += ["};", "#define BB_OFFLINE_BUNDLE_COUNT (sizeof(bb_offline_bundles)/sizeof(bb_offline_bundles[0]))", "#endif", ""]
    output.mkdir(parents=True, exist_ok=True)
    (output / "bb_offline_catalog_generated.h").write_text("\n".join(lines),encoding="ascii",newline="\n")
    (output / "BootBridge.rules.dat").write_bytes(blob)
    return len(rules), hashlib.sha256(blob).hexdigest()

def main() -> int:
    ap=argparse.ArgumentParser(); ap.add_argument("assembly_dir",type=pathlib.Path); ap.add_argument("output_dir",type=pathlib.Path); args=ap.parse_args()
    try:
        count,digest=build(args.assembly_dir,args.output_dir)
    except Exception as e:
        print("offline catalog build refused: %s"%e,file=sys.stderr); return 2
    print("rules=%d sidecar=BootBridge.rules.dat sha256=%s"%(count,digest)); return 0

if __name__ == "__main__": raise SystemExit(main())
