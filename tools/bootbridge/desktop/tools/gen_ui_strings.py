#!/usr/bin/env python3
"""Generate the immutable C string table from the reviewed UI strings."""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import re


def c_string(value: str) -> str:
    # Emit UTF-8 source text. The build pins -finput-charset=UTF-8 and
    # -fexec-charset=UTF-8. Escaping ASCII as \uXXXX is rejected by GCC 14
    # ("not a valid universal character").
    out = []
    for char in value:
        if char == "\\":
            out.append("\\\\")
        elif char == "\"":
            out.append("\\\"")
        elif char == "\n":
            out.append("\\n")
        elif char == "\r":
            out.append("\\r")
        elif char == "\t":
            out.append("\\t")
        elif ord(char) < 0x20 or ord(char) == 0x7f:
            # Fixed-width octal: a hex escape would swallow a following
            # [0-9A-Fa-f] ("\x11Back" is one code unit, not five).
            out.append("\\%03o" % ord(char))
        else:
            out.append(char)
    return "L\"" + "".join(out) + "\""


ALLOWED_PLACEHOLDERS = {"m", "v", "n", "f", "ver"}
TAG = re.compile(r"</?([bu])>")
PLACEHOLDER_CODES = {"\u0001": "m", "\u0002": "v", "\u0003": "n", "\u0004": "f", "\u0005": "ver"}
PLACEHOLDER_ESCAPES = {"m": "\u0001", "v": "\u0002", "n": "\u0003", "f": "\u0004", "ver": "\u0005"}
# Must match BB_UI_MARK_* in gui/bb_ui_text.h.
MARK_END, MARK_STRONG, MARK_UNDERLINE = "\u0010", "\u0011", "\u0012"


def validate_text(value: str, key: str) -> None:
    """Reject unknown placeholders and all inline markup except <b>/<u>."""
    for match in re.finditer(r"\{([^{}]*)\}", value):
        if match.group(1) not in ALLOWED_PLACEHOLDERS:
            raise SystemExit(f"{key}: unknown placeholder {{{match.group(1)}}}")
    stripped = TAG.sub("", value)
    if "<" in stripped or ">" in stripped:
        raise SystemExit(f"{key}: unsupported angle-bracket markup")


def split_tagged(value: str, key: str):
    """Return runs as (style, text), where style is normal/strong/underline."""
    runs = []
    position = 0
    style = "normal"
    for match in TAG.finditer(value):
        if match.start() > position:
            runs.append((style, value[position:match.start()]))
        closing = match.group(0).startswith("</")
        tag_style = "strong" if match.group(1) == "b" else "underline"
        if closing:
            if style != tag_style:
                raise SystemExit(f"{key}: mismatched closing tag")
            style = "normal"
        else:
            if style != "normal":
                raise SystemExit(f"{key}: nested markup")
            style = tag_style
        position = match.end()
    if style != "normal":
        raise SystemExit(f"{key}: unclosed markup")
    if position < len(value):
        runs.append((style, value[position:]))
    return runs


def plain_text(value: str, key: str) -> str:
    validate_text(value, key)
    return TAG.sub("", value)


def marked_text(value: str, key: str) -> str:
    """Keep run order and style without angle brackets in generated C."""
    validate_text(value, key)
    out = []
    for style, text in split_tagged(value, key):
        if style == "normal":
            out.append(text)
        else:
            out.append((MARK_STRONG if style == "strong" else MARK_UNDERLINE) + text + MARK_END)
    return "".join(out)


def encode_placeholders(value: str) -> str:
    """Generated C has no brace placeholders; runtime maps private control codes."""
    def replace(match):
        return PLACEHOLDER_ESCAPES[match.group(1)]
    encoded = re.sub(r"\{([^{}]+)\}", replace, value)
    if "{" in encoded or "}" in encoded:
        raise SystemExit("unencoded placeholder remains")
    return encoded


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("strings", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    raw = args.strings.read_bytes()
    data = json.loads(raw)
    source = data.get("zh", {})
    translated = data.get("en", {})
    if not isinstance(source, dict) or not isinstance(translated, dict) or set(source) != set(translated):
        raise SystemExit("zh/en string key sets differ")
    for key in source:
        if isinstance(source[key], str) and key not in ("steps",):
            validate_text(source[key], "zh." + key)
            validate_text(translated[key], "en." + key)
    lines = [
        "/* Generated by tools/gen_ui_strings.py; do not edit. */",
        "#ifndef BB_UI_STRINGS_GENERATED_H",
        "#define BB_UI_STRINGS_GENERATED_H",
        "#define BB_UI_STRINGS_SCHEMA L\"bootbridge-ui-strings-v1\"",
        "#define BB_UI_STRINGS_SOURCE_SHA256 L\"%s\"" % hashlib.sha256(raw).hexdigest(),
        "typedef enum {",
    ]
    names = {key: "BB_STR_" + key.upper() for key in source}
    # Only scalar strings get a bb_string_id. List-valued keys (steps,
    # s3steps, ...) are emitted as their own tables below; giving them an enum
    # slot while skipping them in bb_strings_zh/en shifted every later ID and
    # left the tail of both tables NULL.
    scalar_keys = []
    for key, value in source.items():
        if key == "steps" or isinstance(value, list):
            if not isinstance(translated[key], list):
                raise SystemExit(f"{key}: zh is a list but en is not")
            continue
        if not isinstance(value, str) or not isinstance(translated[key], str):
            raise SystemExit(f"{key}: zh/en values must both be strings")
        scalar_keys.append(key)
    lines.extend("    %s," % names[key] for key in scalar_keys)
    lines.extend(["    BB_STR_COUNT", "} bb_string_id;"])
    for lang, table in (("zh", source), ("en", translated)):
        lines.append("static const wchar_t *const bb_strings_%s[BB_STR_COUNT] = {" % lang)
        for key in scalar_keys:
            value = table[key]
            if key == "about":
                value = value.replace("0.3.0", "{ver}")
            # Designated initializers bind each text to its own ID.
            lines.append("    [%s] = %s," % (
                names[key], c_string(encode_placeholders(plain_text(value, lang + "." + key)))))
        lines.append("};")
    lines.append("_Static_assert(BB_STR_COUNT == %d, \"one bb_string_id per scalar UI string\");"
                 % len(scalar_keys))
    lines.extend(["static const wchar_t *const bb_strings_zh_steps[6][2] = {"])
    for index in range(6):
        pair = source["steps"][index]
        lines.append("    {%s,%s}," % (c_string(pair[0]), c_string(pair[1])))
    lines.extend(["};", "static const wchar_t *const bb_strings_en_steps[6][2] = {"])
    for index in range(6):
        pair = translated["steps"][index]
        lines.append("    {%s,%s}," % (c_string(pair[0]), c_string(pair[1])))
    lines.extend(["};"])
    for key, value in source.items():
        if key == "steps":
            continue
        if isinstance(value, list):
            if key not in ("s3steps", "s5steps", "s6steps", "faqSteps"):
                raise SystemExit("unexpected list string: " + key)
            lines.append("static const wchar_t *const bb_strings_zh_%s[][2] = {" % key)
            for item in value:
                if isinstance(item, list):
                    validate_text(item[0], "zh." + key + ".title")
                    validate_text(item[1], "zh." + key + ".body")
                    lines.append("    {%s,%s}," % (
                        c_string(encode_placeholders(item[0])),
                        c_string(encode_placeholders(item[1]))))
                else:
                    validate_text(item, "zh." + key + ".step")
                    lines.append("    {%s,NULL}," % c_string(encode_placeholders(item)))
            lines.extend(["};"])
            lines.append("static const wchar_t *const bb_strings_en_%s[][2] = {" % key)
            for item in translated[key]:
                if isinstance(item, list):
                    validate_text(item[0], "en." + key + ".title")
                    validate_text(item[1], "en." + key + ".body")
                    lines.append("    {%s,%s}," % (
                        c_string(encode_placeholders(item[0])),
                        c_string(encode_placeholders(item[1]))))
                else:
                    validate_text(item, "en." + key + ".step")
                    lines.append("    {%s,NULL}," % c_string(encode_placeholders(item)))
            lines.extend(["};"])
            lines.append("static const wchar_t *const bb_strings_zh_%s_runs[][3] = {" % key)
            for item in value:
                if isinstance(item, list):
                    runs = split_tagged(item[1], "zh." + key)
                    lines.append("    {%s,%s,%s}," % tuple(
                        c_string(encode_placeholders(next((text for style, text in runs if style == wanted), "")))
                        for wanted in ("normal", "strong", "underline")))
                else:
                    lines.append("    {%s,NULL,NULL}," % c_string(encode_placeholders(item)))
            lines.extend(["};"])
            lines.append("static const wchar_t *const bb_strings_en_%s_runs[][3] = {" % key)
            for item in translated[key]:
                if isinstance(item, list):
                    runs = split_tagged(item[1], "en." + key)
                    lines.append("    {%s,%s,%s}," % tuple(
                        c_string(encode_placeholders(next((text for style, text in runs if style == wanted), "")))
                        for wanted in ("normal", "strong", "underline")))
                else:
                    lines.append("    {%s,NULL,NULL}," % c_string(encode_placeholders(item)))
            lines.extend(["};"])
    for key, value in source.items():
        if isinstance(value, str) and TAG.search(value):
            runs = split_tagged(value, "zh." + key)
            translated_runs = split_tagged(translated[key], "en." + key)
            for lang, run_list in (("zh", runs), ("en", translated_runs)):
                lines.append("static const wchar_t *const bb_strings_%s_%s_runs[3] = {" % (lang, key))
                lines.append("    %s," % ", ".join(
                    c_string(encode_placeholders(next((text for style, text in run_list if style == wanted), "")))
                    for wanted in ("normal", "strong", "underline")))
                lines.extend(["};"])
    # Ordered styled text for bb_ui_wrap. The *_runs tables above keep only the
    # first run of each style and lose ordering; draw code must use *_marked.
    for lang, table in (("zh", source), ("en", translated)):
        lines.append("static const wchar_t *const bb_strings_%s_marked[BB_STR_COUNT] = {" % lang)
        for key, value in source.items():
            if isinstance(value, str) and TAG.search(value):
                lines.append("    [%s] = %s," % (
                    names[key], c_string(encode_placeholders(marked_text(table[key], lang + "." + key)))))
        lines.extend(["};"])
    lines.extend(["#endif", ""])
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
