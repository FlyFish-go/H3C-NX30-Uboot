#!/usr/bin/env python3
"""Generate exact firmware package allowlists from reviewed OEM catalog47."""
import json, re, sys
from pathlib import Path
HEX = re.compile(r"^[0-9a-f]{64}$")
IDENTITY = re.compile(r"^([A-Z0-9]+)V100(R[0-9]{3}(?:L[0-9]{2})?)$")
def generate(source, models, guard, description):
    doc = json.loads(Path(source).read_text(encoding="utf-8"))
    if doc.get("schema_version") != 1 or not isinstance(doc.get("entries"), list) or len(doc["entries"]) != 47:
        raise ValueError("expected reviewed OEM catalog47 schema v1")
    rows = [row for row in doc["entries"] if row.get("model") in models]
    counts = {m: sum(1 for r in rows if r["model"] == m) for m in models}
    expected = {"RT3000": 16, "RC3000": 14, "RW3000": 11, "NX30": 6}
    if any(counts[m] != expected[m] for m in models):
        raise ValueError("unexpected exact model counts: " + repr(counts))
    lines = [
        "/* Generated by generate_firmware_oem_catalog.py from reviewed catalog47; " + description + ". */",
        "#ifndef " + guard,
        "#define " + guard,
        "struct rt3_oem_fw { const char *model; const char *release; u32 package_bytes; u32 fit_bytes; u32 ubi_bytes; const char *package_sha256; const char *ubi_name; const char *ubi_sha256; };",
        "static const struct rt3_oem_fw rt3_oem_fw_catalog[] = {",
    ]
    seen = set()
    for row in rows:
        model, release = row.get("model"), row.get("release")
        ident = IDENTITY.fullmatch(row.get("header_model_version", ""))
        if not ident or ident.groups() != (model, release):
            raise ValueError("catalog embedded identity mismatch")
        package, fit, ubi = row.get("package_bytes"), row.get("fit_total_size"), row.get("fit_ubi_bytes")
        offset = row.get("fit_offset")
        if not all(isinstance(v, int) and v > 0 for v in (package, fit, ubi)) or not isinstance(offset, int) or offset != 160 or offset + fit > package:
            raise ValueError("invalid package/FIT/UBI dimensions")
        psha, usha = row.get("package_sha256"), row.get("fit_ubi_sha256")
        if not isinstance(psha, str) or not HEX.fullmatch(psha) or not isinstance(usha, str) or not HEX.fullmatch(usha):
            raise ValueError("invalid exact package or extracted UBI hash")
        key = (model, release)
        if key in seen:
            raise ValueError("duplicate model release")
        seen.add(key)
        name = row.get("fit_ubi_image_name")
        if not isinstance(name, str) or not re.fullmatch(r"ubi-[0-9a-f]{40}", name):
            raise ValueError("unexpected FIT path component")
        lines.append("\t{\"%s\", \"%s\", %dU, %dU, %dU, \"%s\", \"%s\", \"%s\"}," %
                     (model, release, package, fit, ubi, psha, name, usha))
    lines.extend(["};", "#endif", ""])
    return "\n".join(lines), counts
if __name__ == "__main__":
    # Every model's firmware has been seen on every board class (an RC3000
    # can be an HW-A, HW-B/D mp02.1 or HW-C board), so all boards share one
    # list; a platform mismatch is only a notice on the rescue page.
    source, output = Path(sys.argv[1]), Path(sys.argv[2])
    models = {"NX30", "RC3000", "RT3000", "RW3000"}
    guard = "__H3C_OEM_FW_CATALOG_H__"
    description = "NX30+RC3000+RT3000+RW3000 exact package allowlist shared by HW-A/B/C/D"
    generated, counts = generate(source, models, guard, description)
    output.write_text(generated, encoding="ascii")
    print("wrote %s: %s" % (output, counts))
