#!/usr/bin/env python3
"""Generate the OEM rootfs hash table from validated catalog metadata."""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DEFAULT_DATA = HERE.parents[2] / "doc" / "RT3000-B-OEM-CATALOG-20261008.json"
DEFAULT_OUT = HERE / "slots_oem_catalog.h"
HEX = re.compile(r"^[0-9a-f]{64}$")
IDENTITY = re.compile(r"^([A-Z0-9]+)V100(R[0-9]{3}(?:L[0-9]{2})?)$")
MAX_ROOTFS_BYTES = 0x02000000


def require(condition, message):
    if not condition:
        raise ValueError(message)


def c_string(value):
    require(isinstance(value, str) and value.isascii(), "C strings must be ASCII")
    require(len(value.encode("ascii")) < 96, "version/label exceeds 95-byte C buffer")
    return json.dumps(value, ensure_ascii=True)


def validate_row(row):
    require(isinstance(row, dict), "catalog entry must be an object")
    model, release = row.get("model"), row.get("release")
    header = row.get("header_model_version")
    match = IDENTITY.fullmatch(header) if isinstance(header, str) else None
    require(match and (model, release) == match.groups(), "model/release disagree with embedded header identity")
    version = model + " " + release
    label = "OEM " + version
    require(row.get("version") == version and row.get("label") == label,
            "version and label must use the canonical embedded identity")
    c_string(version)
    c_string(label)

    for field in ("package_sha256", "fit_ubi_sha256", "kernel_volume_sha256", "rootfs_sha256"):
        value = row.get(field)
        require(isinstance(value, str) and HEX.fullmatch(value), "invalid " + field)
    require(isinstance(row.get("package_bytes"), int) and row["package_bytes"] > 0,
            "invalid package size")
    fit_offset, fit_size = row.get("fit_offset"), row.get("fit_total_size")
    require(isinstance(fit_offset, int) and isinstance(fit_size, int) and
            fit_offset >= 0 and fit_size > 0 and
            fit_offset + fit_size <= row["package_bytes"],
            "invalid FIT bounds metadata")
    require(isinstance(row.get("fit_hashes"), list) and row["fit_hashes"],
            "missing FIT hash verification")
    for item in row["fit_hashes"]:
        require(isinstance(item, dict) and item.get("ok") is True and
                item.get("expected") == item.get("actual"), "FIT hash verification failed")
    require(row.get("rootfs_volume_name") == "ubi_rootfs", "catalog must identify ubi_rootfs")
    require(row.get("rootfs_squashfs_magic") == "hsqs", "rootfs is not little-endian SquashFS")
    used, volume = row.get("rootfs_bytes_used"), row.get("rootfs_volume_bytes")
    require(isinstance(used, int) and isinstance(volume, int) and
            96 <= used <= volume and used <= MAX_ROOTFS_BYTES,
            "invalid SquashFS bytes_used bounds")
    require(row.get("rootfs_squashfs_valid") is True and
            row.get("rootfs_bytes_used") == row.get("rootfs_unsquashfs_reported_bytes"),
            "SquashFS validation or reported size mismatch")
    return row["rootfs_sha256"], version, label


def generate(data_path):
    data = json.loads(Path(data_path).read_text(encoding="utf-8"))
    entries = data.get("entries") if isinstance(data, dict) else None
    if data.get("schema_version") != 1 or not isinstance(entries, list) or not entries:
        raise ValueError("expected nonempty reviewed schema v1 catalog")
    seen = {}
    lines = [
        "/* Generated by generate_slots_oem_catalog.py; do not edit by hand. */",
        "static const struct known_image known_oem[] = {",
    ]
    for row in entries:
        digest, version, label = validate_row(row)
        identity = (version, label)
        if digest in seen and seen[digest] != identity:
            raise ValueError("conflicting identities share rootfs SHA-256: " + digest)
        if digest in seen:
            continue
        seen[digest] = identity
        lines.extend([f" {{ {json.dumps(digest)},",
                      f"   {c_string(version)}, {c_string(label)} }},"])
    lines.extend(["};", ""])
    return "\n".join(lines), len(seen)


if __name__ == "__main__":
    source = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_DATA
    output = Path(sys.argv[2]) if len(sys.argv) > 2 else DEFAULT_OUT
    generated, count = generate(source)
    output.write_text(generated, encoding="ascii")
    print(f"wrote {output}: {count} validated OEM rootfs identities")
